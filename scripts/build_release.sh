#!/bin/bash
set -e

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
VERSION_FILE="$ROOT_DIR/version.json"
PUBSPEC_FILE="$ROOT_DIR/mobile/pubspec.yaml"
DART_VERSION_FILE="$ROOT_DIR/mobile/lib/version.dart"
APK_SOURCE="$ROOT_DIR/mobile/build/app/outputs/flutter-apk/app-release.apk"
APK_DEST="$ROOT_DIR/app-release.apk"

# Dynamic JAVA_HOME without hardcoded personal path
if [ -d "$HOME/.jdk17/Contents/Home" ]; then
  export JAVA_HOME="$HOME/.jdk17/Contents/Home"
elif [ -x "/usr/libexec/java_home" ]; then
  export JAVA_HOME="$(/usr/libexec/java_home -v 17 2>/dev/null || /usr/libexec/java_home)"
fi
export PATH="$JAVA_HOME/bin:$PATH"

# Extract current version and build from version.json
CURRENT_VERSION=$(grep -o '"version": "[^"]*"' "$VERSION_FILE" | cut -d'"' -f4)
CURRENT_BUILD=$(grep -o '"build": [0-9]*' "$VERSION_FILE" | cut -d' ' -f2)

NEW_BUILD=$((CURRENT_BUILD + 1))
RELEASE_DATE=$(date -u +"%Y-%m-%dT%H:%M:%SZ")
CHANGELOG="Backend Go de alta performance com SQLite embarcado e conexao Cloudflare nativa"
RELEASE_ASSET_NAME="AntigravityMobile-v$CURRENT_VERSION-build$NEW_BUILD.apk"
RELEASE_URL="https://github.com/WebuildSoft/antigravity-mobile-releases/releases/latest/download/$RELEASE_ASSET_NAME"

echo "=========================================="
echo "🚀 Iniciando Build do Release (Nativo sem Node)"
echo "Versão: $CURRENT_VERSION (Build #$NEW_BUILD)"
echo "Asset:  $RELEASE_ASSET_NAME"
echo "Data:   $RELEASE_DATE"
echo "=========================================="

# 1. Update version.json
cat <<EOF > "$VERSION_FILE"
{
  "version": "$CURRENT_VERSION",
  "build": $NEW_BUILD,
  "releasedAt": "$RELEASE_DATE",
  "changelog": "$CHANGELOG",
  "downloadUrl": "$RELEASE_URL"
}
EOF
echo "✅ Atualizado version.json"

# 2. Update pubspec.yaml
if [ -f "$PUBSPEC_FILE" ]; then
  sed -i '' "s/^version: .*/version: $CURRENT_VERSION+$NEW_BUILD/" "$PUBSPEC_FILE"
  echo "✅ Atualizado pubspec.yaml para $CURRENT_VERSION+$NEW_BUILD"
fi

# 3. Generate version.dart
cat <<EOF > "$DART_VERSION_FILE"
// AUTO-GENERATED FILE - DO NOT EDIT MANUALLY
// Generated by scripts/build_release.sh at $RELEASE_DATE
class AppVersion {
  static const String version = '$CURRENT_VERSION';
  static const int build = $NEW_BUILD;
  static const String releasedAt = '$RELEASE_DATE';
  static const String changelog = '$CHANGELOG';

  static String get display => 'v\$version (build \$build)';
}
EOF
echo "✅ Gerado mobile/lib/version.dart"

# 4. Build Flutter Web
if [ -d "$ROOT_DIR/mobile" ]; then
  echo ""
  echo "🌐 [1/2] Compilando Flutter Web Release..."
  cd "$ROOT_DIR/mobile"
  flutter build web --release --pwa-strategy=none
  echo "✅ Web compilado com sucesso."

  # 5. Build Android APK
  echo ""
  echo "📱 [2/2] Compilando Android APK Release..."
  flutter build apk --release

  if [ -f "$APK_SOURCE" ]; then
    cp "$APK_SOURCE" "$APK_DEST"
    
    APK_BUILD_FILE="$ROOT_DIR/$RELEASE_ASSET_NAME"
    cp "$APK_SOURCE" "$APK_BUILD_FILE"
    
    APK_GENERIC_FILE="$ROOT_DIR/AntigravityMobile-v$CURRENT_VERSION.apk"
    cp "$APK_SOURCE" "$APK_GENERIC_FILE"

    APK_SIZE=$(ls -lh "$APK_BUILD_FILE" | awk '{print $5}')
    echo "✅ APK copiado para: $APK_BUILD_FILE ($APK_SIZE)"
  fi
fi

# 6. Notify Go server
curl -s -X POST http://127.0.0.1:4040/api/version/notify || true
echo ""
echo "🎉 Release v$CURRENT_VERSION (Build #$NEW_BUILD) concluído com sucesso!"
echo "📦 Arquivo para GitHub Releases: $RELEASE_ASSET_NAME"
