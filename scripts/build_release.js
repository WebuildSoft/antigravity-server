#!/usr/bin/env node

import fs from 'fs';
import path from 'path';
import { execSync } from 'child_process';
import http from 'http';

const ROOT_DIR = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const VERSION_FILE = path.join(ROOT_DIR, 'version.json');
const PUBSPEC_FILE = path.join(ROOT_DIR, 'mobile', 'pubspec.yaml');
const DART_VERSION_FILE = path.join(ROOT_DIR, 'mobile', 'lib', 'version.dart');
const APK_SOURCE = path.join(ROOT_DIR, 'mobile', 'build', 'app', 'outputs', 'flutter-apk', 'app-release.apk');
const APK_DEST = path.join(ROOT_DIR, 'app-release.apk');

// Parse CLI args
const args = process.argv.slice(2);
let customVersion = null;
let customMessage = null;

for (let i = 0; i < args.length; i++) {
  if (args[i] === '--version' && args[i + 1]) {
    customVersion = args[i + 1];
    i++;
  } else if (args[i] === '--message' && args[i + 1]) {
    customMessage = args[i + 1];
    i++;
  }
}

// 1. Read existing version.json
let versionData = { version: '1.2.0', build: 1, changelog: 'Melhorias gerais', downloadUrl: '/app.apk' };
if (fs.existsSync(VERSION_FILE)) {
  try {
    versionData = JSON.parse(fs.readFileSync(VERSION_FILE, 'utf-8'));
  } catch (_) {}
}

if (customVersion) {
  versionData.version = customVersion;
}
if (customMessage) {
  versionData.changelog = customMessage;
}

versionData.build = (parseInt(versionData.build, 10) || 0) + 1;
versionData.releasedAt = new Date().toISOString();

console.log(`\n🚀 Iniciando Build Automático: v${versionData.version} (Build #${versionData.build})`);
console.log(`📝 Changelog: ${versionData.changelog}`);

// 2. Save updated version.json
fs.writeFileSync(VERSION_FILE, JSON.stringify(versionData, null, 2), 'utf-8');
console.log(`✅ Atualizado version.json`);

// 3. Update pubspec.yaml
if (fs.existsSync(PUBSPEC_FILE)) {
  let pubspec = fs.readFileSync(PUBSPEC_FILE, 'utf-8');
  pubspec = pubspec.replace(/^version:.*$/m, `version: ${versionData.version}+${versionData.build}`);
  fs.writeFileSync(PUBSPEC_FILE, pubspec, 'utf-8');
  console.log(`✅ Atualizado pubspec.yaml: version: ${versionData.version}+${versionData.build}`);
}

// 4. Generate mobile/lib/version.dart
const dartContent = `// AUTO-GENERATED FILE - DO NOT EDIT MANUALLY
// Generated by scripts/build_release.js at ${versionData.releasedAt}
class AppVersion {
  static const String version = '${versionData.version}';
  static const int build = ${versionData.build};
  static const String releasedAt = '${versionData.releasedAt}';
  static const String changelog = '${versionData.changelog.replace(/'/g, "\\'")}';

  static String get display => 'v$version (build $build)';
}
`;
fs.writeFileSync(DART_VERSION_FILE, dartContent, 'utf-8');
console.log(`✅ Gerado mobile/lib/version.dart`);

// 5. Build Flutter Web
console.log(`\n🌐 [1/2] Compilando Flutter Web Release...`);
execSync('flutter pub get', {
  cwd: path.join(ROOT_DIR, 'mobile'),
  stdio: 'inherit'
});
execSync('flutter build web --release --pwa-strategy=none', {
  cwd: path.join(ROOT_DIR, 'mobile'),
  stdio: 'inherit'
});
console.log(`✅ Web compilado com sucesso.`);

// 6. Build Android APK
console.log(`\n📱 [2/2] Compilando Android APK Release...`);
const env = {
  ...process.env,
  JAVA_HOME: '/Users/helenilsoncorreadeoliveira/.jdk17/Contents/Home',
  PATH: `/Users/helenilsoncorreadeoliveira/.jdk17/Contents/Home/bin:${process.env.PATH}`
};

execSync('flutter build apk --release', {
  cwd: path.join(ROOT_DIR, 'mobile'),
  env,
  stdio: 'inherit'
});

if (fs.existsSync(APK_SOURCE)) {
  fs.copyFileSync(APK_SOURCE, APK_DEST);
  const stat = fs.statSync(APK_DEST);
  const mb = (stat.size / (1024 * 1024)).toFixed(1);
  console.log(`✅ APK copiado para ${APK_DEST} (${mb} MB)`);
}

// 7. Notify running Node server (if running) about the new version
try {
  const req = http.request({
    hostname: '127.0.0.1',
    port: 4040,
    path: '/api/version/notify',
    method: 'POST',
    timeout: 3000
  }, (res) => {
    console.log(`📢 Servidor notificado sobre a nova versão (status: ${res.statusCode})`);
  });
  req.on('error', () => {});
  req.end();
} catch (_) {}

console.log(`\n🎉 Release v${versionData.version} (Build ${versionData.build}) concluído com sucesso!\n`);
